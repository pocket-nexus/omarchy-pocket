//! Places the profile `pocket build` exported for this program in OUT_DIR. A
//! Linux build links libmali (EGL, GLES and GBM); when cross-compiling,
//! OMARCHY_POCKET_GL_LIBS names a directory holding libmali.so, taken
//! from the device, for the linker.
//!
//! The Android library is one program for every handheld the app runs on:
//! OMARCHY_POCKET_PROFILES names each handheld's exported profile
//! (`pocket_profile.rs`, separated by `;`), and `pocket_profiles.rs` holds
//! them all as `HANDHELDS`, which the app chooses from at its start.
use std::{env, fs, path::PathBuf};

fn main() {
    let android = env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("android");
    pocket_profile_build::emit(if android { pocket_profile_build::Export::Optional } else { pocket_profile_build::Export::Required });
    if android {
        profiles();
    }
    println!("cargo:rerun-if-env-changed=OMARCHY_POCKET_GL_LIBS");
    if env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("linux") {
        if let Ok(dir) = env::var("OMARCHY_POCKET_GL_LIBS") {
            println!("cargo:rustc-link-search=native={dir}");
        }
    }
}

/// `OUT_DIR/pocket_profiles.rs`: a module per exported profile and the
/// `HANDHELDS` table over them, in the order given.
fn profiles() {
    println!("cargo:rerun-if-env-changed=OMARCHY_POCKET_PROFILES");
    let out = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR"));
    let list = env::var("OMARCHY_POCKET_PROFILES")
        .expect("OMARCHY_POCKET_PROFILES is unset: build the Android library with tools/android.ts lib, which exports each handheld's profile");
    let mut modules = String::new();
    let mut table = String::from("pub static HANDHELDS: &[Handheld] = &[\n");
    for (index, path) in list.split(';').filter(|p| !p.is_empty()).enumerate() {
        println!("cargo:rerun-if-changed={path}");
        let text = fs::read_to_string(path).unwrap_or_else(|e| panic!("OMARCHY_POCKET_PROFILES: {path}: {e}"));
        assert!(text.starts_with("// Generated by pocket host export"), "{path} is not a pocket host export");
        let name = format!("handheld_{index}.rs");
        fs::write(out.join(&name), text).expect("write a handheld's profile");
        modules.push_str(&format!(
            "#[allow(dead_code)]\nmod handheld_{index} {{\n    include!(concat!(env!(\"OUT_DIR\"), \"/{name}\"));\n}}\n"
        ));
        table.push_str(&format!(
            "    Handheld {{ id: handheld_{index}::ID, host_abi: handheld_{index}::HOST_ABI, hash: handheld_{index}::PROFILE_HASH, profile: handheld_{index}::profile }},\n"
        ));
    }
    table.push_str("];\n");
    assert!(modules.contains("mod handheld_0"), "OMARCHY_POCKET_PROFILES names no profile");
    fs::write(out.join("pocket_profiles.rs"), modules + &table).expect("write pocket_profiles.rs");
}
